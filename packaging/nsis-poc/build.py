"""Build isolated previews or the standalone native NSIS installer. Never runs Setup."""
import argparse
import json
import os
from pathlib import Path
import shutil
import subprocess
import tomllib

ROOT = Path(__file__).resolve().parents[2]
HERE = Path(__file__).resolve().parent


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--renderer", choices=["raster", "svg"], default="svg")
    parser.add_argument("--maintenance", action="store_true", help="Build a harmless maintenance-screen fixture")
    parser.add_argument("--installer", action="store_true", help="Build the real, privileged installer (never execute it)")
    args = parser.parse_args()
    if args.installer and args.maintenance:
        parser.error("--installer and --maintenance cannot be combined")
    if args.installer and args.renderer != "svg":
        parser.error("The real installer uses the native SVG renderer")
    if os.name != "nt":
        raise SystemExit("This proof of concept requires Windows and the MSVC toolchain.")
    makensis = shutil.which("makensis")
    if not makensis:
        candidate = Path(os.environ.get("ProgramFiles(x86)", "C:/Program Files (x86)")) / "NSIS/makensis.exe"
        if candidate.is_file():
            makensis = str(candidate)
    if not makensis:
        raise SystemExit("Install stock NSIS 3 (Unicode). No NSIS rebuild is needed.")
    (ROOT / "artifacts").mkdir(exist_ok=True)
    if args.renderer == "raster":
        subprocess.run(["node", str(HERE / "generate-icon.mjs")], cwd=ROOT, check=True, timeout=60)
    elif not (ROOT / "crates/switchboot_core/icons/icon.ico").is_file():
        subprocess.run(["node", "packaging/generate-app-icons.mjs"], cwd=ROOT, check=True, timeout=60)
    common = ["--locked", "--release", "--target", "i686-pc-windows-msvc",
              "--manifest-path", str(HERE / "ui/Cargo.toml")]
    if args.renderer == "svg":
        common += ["--features", "native-svg"]
    if args.installer:
        common += ["--features", "installer"]
        subprocess.run(["pnpm", "icons"], cwd=ROOT, shell=True, check=True, timeout=120)
        subprocess.run(["node", "packaging/generate-app-icons.mjs"], cwd=ROOT, check=True, timeout=60)
        subprocess.run(["cargo", "build", "--locked", "--release", "--bin", "switchboot"], cwd=ROOT, check=True, timeout=600)
    subprocess.run(["cargo", "build", *common], cwd=ROOT, check=True, timeout=180)
    dll = HERE / "ui/target/i686-pc-windows-msvc/release/switchboot_nsis_ui.dll"
    subprocess.run(["cargo", "run", *common, "--example", "check_plugin", "--", str(dll)],
                   cwd=ROOT, check=True, timeout=60)
    output = ROOT / f"artifacts/Switchboot_NSIS-preview-{args.renderer}.exe"
    defines = [f"-DPOC_OUTPUT={output}"]
    if args.renderer == "svg":
        defines.append("-DNATIVE_SVG")
    if args.maintenance:
        output = ROOT / "artifacts/Switchboot_NSIS-maintenance-preview.exe"
        defines = [f"-DPOC_OUTPUT={output}", "-DPOC_MAINTENANCE"]
        if args.renderer == "svg":
            defines.append("-DNATIVE_SVG")
    script = HERE / "setup.nsi"
    if args.installer:
        version = tomllib.loads((ROOT / "Cargo.toml").read_text())["package"]["version"]
        output = ROOT / "artifacts/Switchboot_x64-nsis-setup.exe"
        defines = [f"-DVERSION={version}", f"-DOUTPUT={output}"]
        script = ROOT / "packaging/nsis/setup.nsi"
        icons = sorted((ROOT / "crates/switchboot_core/resources/icons/ico").glob("*.ico"))
        if not icons:
            raise SystemExit("Generated shortcut icons are missing")
        (script.parent / "owned-icons.nsh").write_text("; Generated by build.py; do not commit.\n" + "".join(
            f'Delete "$INSTDIR\\resources\\icons\\ico\\{icon.name}"\n' for icon in icons))
    subprocess.run([makensis, "-WX", "-V3", *defines, str(script)], cwd=ROOT, check=True, timeout=120)
    metadata = {"renderer": args.renderer, "real_installer": args.installer, "installer_bytes": output.stat().st_size,
                "ui_dll_bytes": dll.stat().st_size}
    output.with_suffix(".build.json").write_text(json.dumps(metadata, indent=2))
    print(f"Built {output} ({output.stat().st_size} bytes); UI DLL: {dll.stat().st_size} bytes")


if __name__ == "__main__":
    main()
